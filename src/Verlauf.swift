import Cocoa
import CryptoKit
import Vision

enum Art: String, Codable { case text, bild, datei }

struct Eintrag: Codable, Equatable {
    var id: String
    var art: Art
    /// Text: der Inhalt. Bild: der erkannte Text (für Suche und „Text aus Bild“), sobald die Erkennung gelaufen ist.
    var text: String?
    var dateien: [String]?
    /// Dateiname im Ordner `bilder/`
    var bild: String?
    var breite: Int?
    var hoehe: Int?
    var app: String?
    var bundle: String?
    var zeit: Date
    var angeheftetAm: Date?
    var erkannt: Bool?
    var hash: String

    var angeheftet: Bool { angeheftetAm != nil }
}

/// Was gerade in der Zwischenablage liegt, schon ausgelesen.
enum Inhalt {
    case text(String)
    case bild(Data, Int, Int)
    case dateien([URL])
}

enum VerlaufFehler: LocalizedError {
    case meldung(String)
    var errorDescription: String? { if case .meldung(let t) = self { return t }; return nil }
}

/// Der Verlauf liegt in `~/Library/Application Support/Hikidashi/`: `verlauf.json` und Bilder in `bilder/`.
/// Bewusst nicht im Projektordner: In der Zwischenablage landen auch Privates und Kundendaten.
final class Verlauf {
    static let maxEintraege = 300
    static let maxBilder = 60
    static let maxTextBytes = 2_000_000
    static let maxBildBytes = 40_000_000
    /// Breite × Höhe: Ein kleines PNG kann riesige Maße haben und beim Entpacken den Speicher sprengen.
    static let maxBildPixel = 100_000_000

    /// Typen, die Passwort-Manager und andere Apps setzen, wenn etwas nicht in einen Verlauf gehört.
    static let ignorierteTypen: Set<String> = [
        "org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType", "org.nspasteboard.AutoGeneratedType",
        "com.agilebits.onepassword", "de.petermaurer.TransientPasteboardType", "com.typeit4me.clipping",
        "Pasteboard generator type", "com.apple.is-remote-clipboard.ignored",
    ]
    static let ignorierteApps: Set<String> = [
        "com.apple.keychainaccess", "com.apple.Passwords", "com.1password.1password", "com.agilebits.onepassword7",
        "com.bitwarden.desktop", "com.dashlane.dashlanephonefinal", "com.lastpass.LastPass", "org.keepassxc.keepassxc",
        "me.proton.pass.electron", "com.markmcguill.strongbox.mac", "in.sinew.Enpass-Desktop", "com.hicknhacksoftware.MacPass",
        "net.antelle.keeweb",
    ]

    let ordner: URL
    var bilderOrdner: URL { ordner.appendingPathComponent("bilder") }
    var datei: URL { ordner.appendingPathComponent("verlauf.json") }
    private(set) var eintraege: [Eintrag] = []
    var geaendert: (() -> Void)?

    init(ordner: URL) {
        self.ordner = ordner
        let fm = FileManager.default
        try? fm.createDirectory(at: bilderOrdner, withIntermediateDirectories: true)
        // Nur für dich lesbar und nicht im Time-Machine-Backup: Leeren soll den Verlauf wirklich loswerden.
        for o in [ordner, bilderOrdner] { try? fm.setAttributes([.posixPermissions: 0o700], ofItemAtPath: o.path) }
        let bilder = (try? fm.contentsOfDirectory(at: bilderOrdner, includingPropertiesForKeys: nil)) ?? []
        for d in bilder + [datei] { try? fm.setAttributes([.posixPermissions: 0o600], ofItemAtPath: d.path) }
        var ohneBackup = URLResourceValues(); ohneBackup.isExcludedFromBackup = true
        var o = ordner; try? o.setResourceValues(ohneBackup)
        laden()
    }

    /// Schreibt so, dass nur du die Datei lesen kannst.
    static func schreibePrivat(_ daten: Data, nach url: URL) throws {
        try daten.write(to: url, options: .atomic)
        try FileManager.default.setAttributes([.posixPermissions: 0o600], ofItemAtPath: url.path)
    }

    /// Nur `<UUID>.png` gilt als Bildname. Ein veränderter `verlauf.json` soll keine Dateien außerhalb von `bilder/` erreichen.
    static func gueltigerBildname(_ name: String) -> Bool {
        name.hasSuffix(".png") && UUID(uuidString: String(name.dropLast(4))) != nil
    }

    static var standardOrdner: URL {
        FileManager.default.urls(for: .applicationSupportDirectory, in: .userDomainMask)[0].appendingPathComponent("Hikidashi")
    }

    // MARK: Laden und Sichern

    func laden() {
        guard let daten = try? Data(contentsOf: datei) else { return }
        let d = JSONDecoder(); d.dateDecodingStrategy = .iso8601
        eintraege = (try? d.decode([Eintrag].self, from: daten)) ?? []
    }

    func sichern() {
        let e = JSONEncoder(); e.dateEncodingStrategy = .iso8601
        if let daten = try? e.encode(eintraege) { try? Verlauf.schreibePrivat(daten, nach: datei) }
        geaendert?()
    }

    // MARK: Ändern

    /// Nimmt einen neuen Inhalt auf. Gab es ihn schon, wandert der alte Eintrag nach oben.
    @discardableResult
    func aufnehmen(_ inhalt: Inhalt, app: String?, bundle: String?, jetzt: Date = Date()) -> Eintrag? {
        var neu: Eintrag
        switch inhalt {
        case .text(let t):
            guard t.utf8.count <= Verlauf.maxTextBytes else { return nil }
            neu = Eintrag(id: UUID().uuidString, art: .text, text: t, zeit: jetzt, hash: "t:" + Verlauf.hash(Data(t.utf8)))
        case .bild(let png, let b, let h):
            guard png.count <= Verlauf.maxBildBytes, b * h <= Verlauf.maxBildPixel else { return nil }
            neu = Eintrag(id: UUID().uuidString, art: .bild, breite: b, hoehe: h, zeit: jetzt, hash: "b:" + Verlauf.hash(png))
            if let i = eintraege.firstIndex(where: { $0.hash == neu.hash }) { return nachOben(i, app: app, bundle: bundle, jetzt: jetzt) }
            let name = neu.id + ".png"
            do { try Verlauf.schreibePrivat(png, nach: bilderOrdner.appendingPathComponent(name)) } catch { return nil }
            neu.bild = name
        case .dateien(let urls):
            let pfade = urls.map(\.path)
            neu = Eintrag(id: UUID().uuidString, art: .datei, dateien: pfade, zeit: jetzt, hash: "d:" + Verlauf.hash(Data(pfade.joined(separator: "\n").utf8)))
        }
        if let i = eintraege.firstIndex(where: { $0.hash == neu.hash }) { return nachOben(i, app: app, bundle: bundle, jetzt: jetzt) }
        neu.app = app; neu.bundle = bundle
        eintraege.insert(neu, at: 0)
        aufraeumen()
        sichern()
        return neu
    }

    private func nachOben(_ i: Int, app: String?, bundle: String?, jetzt: Date) -> Eintrag {
        var e = eintraege.remove(at: i)
        e.zeit = jetzt
        if app != nil { e.app = app; e.bundle = bundle }
        eintraege.insert(e, at: 0)
        sichern()
        return e
    }

    /// Ein Eintrag wurde eingefügt oder kopiert: nach oben damit.
    func benutzt(_ id: String, jetzt: Date = Date()) {
        guard let i = eintraege.firstIndex(where: { $0.id == id }) else { return }
        _ = nachOben(i, app: nil, bundle: nil, jetzt: jetzt)
    }

    func anheften(_ id: String, _ an: Bool, jetzt: Date = Date()) {
        guard let i = eintraege.firstIndex(where: { $0.id == id }) else { return }
        eintraege[i].angeheftetAm = an ? jetzt : nil
        aufraeumen()
        sichern()
    }

    func setzeErkannt(_ id: String, _ text: String) {
        guard let i = eintraege.firstIndex(where: { $0.id == id }) else { return }
        eintraege[i].text = text.isEmpty ? nil : text
        eintraege[i].erkannt = true
        sichern()
    }

    func loeschen(_ id: String) {
        guard let i = eintraege.firstIndex(where: { $0.id == id }) else { return }
        entferneBild(eintraege[i])
        eintraege.remove(at: i)
        sichern()
    }

    /// Leert den Verlauf. Angeheftetes bleibt.
    func leeren() {
        for e in eintraege where !e.angeheftet { entferneBild(e) }
        eintraege.removeAll { !$0.angeheftet }
        sichern()
    }

    private func entferneBild(_ e: Eintrag) {
        if let url = bildURL(e) { try? FileManager.default.removeItem(at: url) }
    }

    /// Hält den Verlauf klein: höchstens 300 Einträge und 60 Bilder, Angeheftetes zählt nicht mit.
    private func aufraeumen() {
        var anzahl = 0, bilder = 0
        var behalten: [Eintrag] = []
        for e in eintraege {
            if e.angeheftet { behalten.append(e); continue }
            anzahl += 1
            if e.art == .bild { bilder += 1 }
            if anzahl > Verlauf.maxEintraege || (e.art == .bild && bilder > Verlauf.maxBilder) { entferneBild(e); continue }
            behalten.append(e)
        }
        eintraege = behalten
    }

    // MARK: Lesen

    func bildURL(_ e: Eintrag) -> URL? {
        e.bild.flatMap { Verlauf.gueltigerBildname($0) ? bilderOrdner.appendingPathComponent($0) : nil }
    }

    func eintrag(_ id: String) -> Eintrag? { eintraege.first { $0.id == id } }

    /// 0 = Verlauf (neueste oben), 1 = Angeheftet (zuletzt angeheftet oben), 2 = Bilder
    func liste(reiter: Int, suche: String) -> [Eintrag] {
        var l: [Eintrag]
        switch reiter {
        case 1: l = eintraege.filter(\.angeheftet).sorted { $0.angeheftetAm! > $1.angeheftetAm! }
        case 2: l = eintraege.filter { $0.art == .bild }
        default: l = eintraege
        }
        let s = suche.trimmingCharacters(in: .whitespaces)
        guard !s.isEmpty else { return l }
        let woerter = s.split(separator: " ").map(String.init)
        return l.filter { e in
            let heu = [e.text ?? "", (e.dateien ?? []).joined(separator: " "), e.app ?? ""].joined(separator: " ")
            return woerter.allSatisfy { heu.range(of: $0, options: [.caseInsensitive, .diacriticInsensitive]) != nil }
        }
    }

    // MARK: Zwischenablage

    static func hash(_ d: Data) -> String { SHA256.hash(data: d).map { String(format: "%02x", $0) }.joined() }

    static func ignorieren(_ pb: NSPasteboard) -> Bool {
        (pb.types ?? []).contains { ignorierteTypen.contains($0.rawValue) }
    }

    /// Liest die Zwischenablage. Reihenfolge: Dateien aus dem Finder, dann Text, dann Bild.
    /// Ausnahme: Ist der Text nur eine Web-Adresse und liegt ein Bild daneben (Browser „Bild kopieren“), zählt das Bild.
    static func lies(_ pb: NSPasteboard) -> Inhalt? {
        if ignorieren(pb) { return nil }
        if let urls = pb.readObjects(forClasses: [NSURL.self], options: [.urlReadingFileURLsOnly: true]) as? [URL], !urls.isEmpty {
            return .dateien(urls)
        }
        let text = pb.string(forType: .string)
        let hatText = !(text?.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty ?? true)
        let typen = pb.types ?? []
        let hatBild = typen.contains(.png) || typen.contains(.tiff)
        if hatText, let text {
            let t = text.trimmingCharacters(in: .whitespacesAndNewlines)
            let nurAdresse = !t.contains(" ") && !t.contains("\n") && (t.hasPrefix("http://") || t.hasPrefix("https://"))
            if !(hatBild && nurAdresse) { return .text(text) }
        }
        if hatBild, let bild = pngAus(pb) { return bild }
        return nil
    }

    static func pngAus(_ pb: NSPasteboard) -> Inhalt? {
        if let png = pb.data(forType: .png), let rep = NSBitmapImageRep(data: png) {
            guard rep.pixelsWide * rep.pixelsHigh <= maxBildPixel else { return nil }
            return .bild(png, rep.pixelsWide, rep.pixelsHigh)
        }
        guard let tiff = pb.data(forType: .tiff), let rep = NSBitmapImageRep(data: tiff),
              rep.pixelsWide * rep.pixelsHigh <= maxBildPixel,
              let png = rep.representation(using: .png, properties: [:]) else { return nil }
        return .bild(png, rep.pixelsWide, rep.pixelsHigh)
    }

    /// Legt einen Eintrag zurück in die Zwischenablage.
    func schreibe(_ e: Eintrag, auf pb: NSPasteboard) {
        pb.clearContents()
        switch e.art {
        case .text:
            pb.setString(e.text ?? "", forType: .string)
        case .bild:
            guard let url = bildURL(e), let png = try? Data(contentsOf: url) else { return }
            pb.declareTypes([.png, .tiff], owner: nil)
            pb.setData(png, forType: .png)
            if let tiff = NSBitmapImageRep(data: png)?.tiffRepresentation { pb.setData(tiff, forType: .tiff) }
        case .datei:
            pb.writeObjects((e.dateien ?? []).map { URL(fileURLWithPath: $0) as NSURL })
        }
    }

    // MARK: Text aus Bild

    /// Erkennt Text auf einem Bild, lokal mit Apples Vision. Deutsch, Englisch, Chinesisch und Japanisch.
    static func erkenneText(_ url: URL) throws -> String {
        guard let quelle = CGImageSourceCreateWithURL(url as CFURL, nil),
              let werte = CGImageSourceCopyPropertiesAtIndex(quelle, 0, nil) as? [CFString: Any],
              let b = werte[kCGImagePropertyPixelWidth] as? Int, let h = werte[kCGImagePropertyPixelHeight] as? Int,
              b * h <= maxBildPixel,
              let bild = CGImageSourceCreateImageAtIndex(quelle, 0, nil) else { throw VerlaufFehler.meldung("Bild nicht lesbar") }
        let anfrage = VNRecognizeTextRequest()
        anfrage.recognitionLevel = .accurate
        anfrage.usesLanguageCorrection = true
        anfrage.automaticallyDetectsLanguage = true
        anfrage.recognitionLanguages = ["de-DE", "en-US", "zh-Hans", "ja-JP"]
        try VNImageRequestHandler(cgImage: bild).perform([anfrage])
        return (anfrage.results ?? []).compactMap { $0.topCandidates(1).first?.string }.joined(separator: "\n")
    }

    // MARK: Inbox

    /// Legt einen Eintrag als Datei in den Inbox-Ordner. Text wird eine .md, Bild eine .png, Dateien werden kopiert.
    static func inDieInbox(_ e: Eintrag, verlauf: Verlauf, inbox: URL, jetzt: Date = Date()) throws -> [URL] {
        let fm = FileManager.default
        guard fm.fileExists(atPath: inbox.path) else { throw VerlaufFehler.meldung("Den Inbox-Ordner gibt es nicht: \(inbox.path)") }
        let f = DateFormatter(); f.locale = Locale(identifier: "de_DE"); f.dateFormat = "yyyy-MM-dd-HHmm"
        let stempel = f.string(from: jetzt)
        func frei(_ name: String, _ endung: String) -> URL {
            func url(_ n: String) -> URL { inbox.appendingPathComponent(endung.isEmpty ? n : "\(n).\(endung)") }
            var u = url(name), n = 2
            while fm.fileExists(atPath: u.path) { u = url("\(name)-\(n)"); n += 1 }
            return u
        }
        switch e.art {
        case .text:
            let text = e.text ?? ""
            let ziel = frei("\(stempel)-\(kurzname(text))", "md")
            let f2 = DateFormatter(); f2.locale = Locale(identifier: "de_DE"); f2.dateFormat = "yyyy-MM-dd"
            let quelle = "Hikidashi" + (e.app.map { " (kopiert aus \($0))" } ?? "")
            let kopf = "---\ntags: [inbox]\nerstellt: \(f2.string(from: jetzt))\nquelle: \(yamlText(quelle))\n---\n\n"
            try (kopf + text + (text.hasSuffix("\n") ? "" : "\n")).write(to: ziel, atomically: true, encoding: .utf8)
            return [ziel]
        case .bild:
            guard let quelle = verlauf.bildURL(e) else { throw VerlaufFehler.meldung("Bild fehlt") }
            let ziel = frei("\(stempel)-bild", "png")
            try fm.copyItem(at: quelle, to: ziel)
            return [ziel]
        case .datei:
            var ziele: [URL] = []
            // Nur einzelne Dateien bis 200 MB, keine Ordner: die Inbox ist für Gedanken, nicht für Projektordner.
            for pfad in e.dateien ?? [] {
                var ordner: ObjCBool = false
                guard fm.fileExists(atPath: pfad, isDirectory: &ordner), !ordner.boolValue,
                      let groesse = (try? fm.attributesOfItem(atPath: pfad))?[.size] as? Int, groesse <= 200_000_000 else { continue }
                let url = URL(fileURLWithPath: pfad)
                let ziel = frei(url.deletingPathExtension().lastPathComponent, url.pathExtension)
                try fm.copyItem(at: url, to: ziel)
                ziele.append(ziel)
            }
            if ziele.isEmpty { throw VerlaufFehler.meldung("Nichts zum Ablegen: Ordner, sehr große oder gelöschte Dateien gehen nicht in die Inbox.") }
            return ziele
        }
    }

    /// Text in Anführungszeichen für den YAML-Kopf, damit ein App-Name mit `:` oder Zeilenumbruch ihn nicht zerlegt.
    static func yamlText(_ s: String) -> String {
        let innen = s.replacingOccurrences(of: "\\", with: "\\\\").replacingOccurrences(of: "\"", with: "\\\"")
            .replacingOccurrences(of: "\n", with: " ").replacingOccurrences(of: "\r", with: " ")
        return "\"\(innen)\""
    }

    /// Die ersten Wörter als Dateiname: „Idee für das nächste Video“ → „idee-fuer-das-naechste-video“
    static func kurzname(_ text: String) -> String {
        var s = text.lowercased()
        for (a, b) in [("ä", "ae"), ("ö", "oe"), ("ü", "ue"), ("ß", "ss")] { s = s.replacingOccurrences(of: a, with: b) }
        let woerter = s.components(separatedBy: CharacterSet.alphanumerics.inverted).filter { !$0.isEmpty && $0.allSatisfy(\.isASCII) }
        let name = woerter.prefix(6).joined(separator: "-")
        return name.isEmpty ? "notiz" : String(name.prefix(50))
    }
}
